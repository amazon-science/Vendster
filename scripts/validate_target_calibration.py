"""
Target-calibration validation (paper appendix artifact) for Vendster.

Confirms that the environment's per-basket sales target — the P{XX} (default P80) of
each basket's total-sales distribution under the uniform-random-discount REFERENCE
POLICY over the DGP — is well-calibrated: the *no-forecast* Buyer lands near the
by-construction reference-policy attainment (100−XX)%. For each of ``--baskets`` sampled
5-baskets we (1) compute the analytic P{XX} target (no LLM), then (2) run ``--episodes``
no-forecast negotiation episodes at that target. We report POOLED attainment with a Wilson
95% CI and a two-sided exact binomial test against the reference expectation (100−XX)%,
plus the LLM-vs-reference offset and the per-basket breakdown.

Note: the P80 operating point is selected *effect-blind* (via the Stage-1 difficulty sweep,
see the paper's Environment Setup appendix) — this script validates target CALIBRATION, it does NOT choose
the percentile.

    # real (Bedrock):
    uv run python scripts/validate_target_calibration.py \
        --model bedrock --baskets 8 --episodes 20 --out experiments/target_calibration

    # smoke (mock, meaningless attainment but exercises the artifact):
    uv run python scripts/validate_target_calibration.py \
        --model mock --baskets 2 --episodes 4 --panel-size 200 --out experiments/tc_smoke
"""

import argparse
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import vendster.forecasters  # noqa: F401  register forecasters
from vendster.llm import add_llm_args, make_llm
from vendster.data.m5 import M5DataSource
from vendster.experiment import validate_xx


def _fmt_pct(x):
    return "n/a" if x != x else f"{x*100:.1f}%"       # x!=x → NaN


def write_markdown(v: dict, args, elapsed: float, path: Path):
    p = v["pooled"]
    b = v["by_basket"]
    lo, hi = p["wilson_ci95"]
    lines = [
        f"# Appendix — Target Calibration Validation (P{v['percentile']:.0f})",
        "",
        f"**Claim.** The per-basket sales target (P{v['percentile']:.0f} of each basket's total-sales "
        "distribution under the uniform-random-discount reference policy over the DGP) is "
        f"well-calibrated: the no-forecast Buyer lands near the by-construction reference-policy "
        f"attainment {_fmt_pct(v['reference_attainment'])} (= 100−XX%). The P80 operating point "
        "itself is chosen effect-blind (see the paper), not by this script.",
        "",
        f"**Setup.** {b['n_baskets']} sampled 5-baskets from the {args._pool_size}-product "
        f"pool (stable sell-price CV<5% and min weekly units ≥ {args.min_weekly}); "
        f"{args.episodes} no-forecast episodes per basket ({p['n']} total); model "
        f"`{args.model}`; seed {args.seed}; analytic target from {args.ref_draws} "
        f"reference-policy DGP draws per basket.",
        "",
        "## Pooled result",
        "",
        "| metric | value |",
        "|---|---|",
        f"| no-forecast attainment | **{_fmt_pct(p['attainment'])}** ({p['successes']}/{p['n']}) |",
        f"| Wilson 95% CI | [{_fmt_pct(lo)}, {_fmt_pct(hi)}] |",
        f"| two-sided binomial test vs reference {_fmt_pct(v['reference_attainment'])} | p = {p['binom_p_vs_ref']:.3f} |",
        f"| reference inside 95% CI? | {'yes' if p['consistent_with_ref'] else 'no'} |",
        f"| by-basket mean ± SD | {_fmt_pct(b['mean'])} ± {_fmt_pct(b['sd'])} |",
        "",
        "**Conclusion.** "
        + (f"The no-forecast baseline is statistically **consistent with the reference-policy "
           f"attainment** {_fmt_pct(v['reference_attainment'])} "
           f"(p = {p['binom_p_vs_ref']:.3f}; reference within the 95% CI), so the analytic "
           "P{:.0f} target is well-calibrated to the DGP.".format(v['percentile'])
           if p["consistent_with_ref"] else
           f"The no-forecast baseline offset from the reference: {v['recentre']['note']} "
           "(the LLM negotiates better/worse than the uniform-random reference policy)."),
        "",
        "## Per-basket breakdown",
        "",
        "| basket | target ($) | attainment | n | Wilson 95% CI |",
        "|---|---|---|---|---|",
    ]
    for i, pb in enumerate(v["per_basket"]):
        clo, chi = pb["ci95"]
        lines.append(f"| {i} | {pb['target']:,.0f} | {_fmt_pct(pb['attainment'])} "
                     f"| {pb['n']} | [{_fmt_pct(clo)}, {_fmt_pct(chi)}] |")
    lines += ["",
              f"_Generated by `scripts/validate_target_calibration.py` in "
              f"{elapsed:.0f}s; git sha `{v['manifest']['git_sha'][:10]}`._"]
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    add_llm_args(ap, default="mock")
    ap.add_argument("--baskets", type=int, default=8)
    ap.add_argument("--episodes", type=int, default=20, help="no-forecast episodes per basket")
    ap.add_argument("--percentile", type=float, default=80.0)
    ap.add_argument("--ref-draws", type=int, default=2000)
    ap.add_argument("--min-weekly", type=int, default=5)
    ap.add_argument("--panel-size", type=int, default=1500)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="experiments/target_calibration")
    args = ap.parse_args()

    t0 = time.time()
    print(f"[{time.strftime('%H:%M:%S')}] M5 pool (min-week>={args.min_weekly})...", flush=True)
    source = M5DataSource(min_weekly=args.min_weekly, panel_size=args.panel_size)
    args._pool_size = len(source.pool())
    print(f"  pool={args._pool_size}; {args.baskets} baskets x {args.episodes} "
          f"no-forecast eps at P{args.percentile:.0f}", flush=True)
    llm = make_llm(args.model, args.model_id)

    v = validate_xx(source, llm, n_baskets=args.baskets, episodes=args.episodes,
                    percentile=args.percentile, seed=args.seed, ref_draws=args.ref_draws,
                    out_dir=args.out, model_name=args.model_id or args.model)

    out = Path(args.out)
    write_markdown(v, args, time.time() - t0, out / "calibration_report.md")

    p = v["pooled"]
    lo, hi = p["wilson_ci95"]
    print(f"\n[pooled] no-forecast attainment = {_fmt_pct(p['attainment'])} "
          f"({p['successes']}/{p['n']})", flush=True)
    print(f"  Wilson 95% CI = [{_fmt_pct(lo)}, {_fmt_pct(hi)}]  "
          f"binom p vs ref {_fmt_pct(v['reference_attainment'])} = {p['binom_p_vs_ref']:.3f}  "
          f"ref in CI: {p['consistent_with_ref']}", flush=True)
    print(f"  by-basket mean +/- SD = {_fmt_pct(v['by_basket']['mean'])} "
          f"+/- {_fmt_pct(v['by_basket']['sd'])}", flush=True)
    print(f"  {v['recentre']['note']}", flush=True)
    print(f"\nDONE in {time.time()-t0:.0f}s -> {out}/ (validation.json + calibration_report.md)",
          flush=True)


if __name__ == "__main__":
    main()
